import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { parseArgs } from 'node:util';
import { infrastructureBudgets } from './catalog.mjs';
import { writeJSON } from './receipts.mjs';
import { runProcess, npmCommand, nodeCommand } from './process.mjs';
import { dependencyInstallArgs, npmLogEnvironment } from './dependency-install.mjs';
const split=process.argv.indexOf('--');assert(split>=0,'Use -- before the actual infrastructure command');
const {values}=parseArgs({args:process.argv.slice(2,split),options:{kind:{type:'string'},output:{type:'string'},profile:{type:'string'}}});
assert(['install','download'].includes(values.kind)&&values.output);
const [file,...args]=process.argv.slice(split+1);assert(file);
if (values.kind === 'install') {
  assert.deepEqual([file, ...args], ['npm', 'ci', '--no-audit', '--no-fund'], 'Use the declared locked dependency install');
  args.splice(0, args.length, ...dependencyInstallArgs(values.profile));
} else assert(!values.profile, 'Download does not take an install profile');
const command=file==='node'?nodeCommand(args):file==='npm'?npmCommand(args):{file,args};
const startedAt=new Date().toISOString(),deadline=Date.now()+infrastructureBudgets[values.kind];
const destination=path.join(values.output,'infrastructure',`${values.kind}.json`);
const env=values.kind==='install'?npmLogEnvironment(process.env,path.join(values.output,'infrastructure','npm-debug')):process.env;
const observed=await runProcess(command.file,command.args,{deadline,env,logPath:destination.replace('.json','.log')});
await writeJSON(destination,{schemaVersion:1,kind:values.kind,...(values.profile?{profile:values.profile,args}:{}),startedAt,completedAt:new Date().toISOString(),deadline,...observed});
if(observed.status!=='passed')process.exitCode=1;
